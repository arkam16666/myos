#!/usr/bin/env python3
"""mkrt - build MyOS Java's runtime library: compile ports/java/lib/**/*.java
with javac and pack the classes into a jar embedded in the VM as a C array.

usage: python ports/java/mkrt.py OUT_HEADER [--jar OUT.jar]
Exit code 3 = no javac found (the build skips Java then).
"""
import io
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))


def find_javac():
    exe = "javac.exe" if os.name == "nt" else "javac"
    for var in ("JAVA_HOME", "JDK_HOME"):
        home = os.environ.get(var)
        if home and os.path.exists(os.path.join(home, "bin", exe)):
            return os.path.join(home, "bin", exe)
    found = shutil.which("javac")
    if found:
        return found
    if os.name == "nt":                     # usual Windows install places
        for base in (r"C:\Program Files\Microsoft", r"C:\Program Files\Eclipse Adoptium", r"C:\Program Files\Java",
                     r"C:\Program Files\OpenJDK"):
            if os.path.isdir(base):
                for d in sorted(os.listdir(base), reverse=True):
                    p = os.path.join(base, d, "bin", exe)
                    if os.path.exists(p):
                        return p
    if sys.platform == "darwin":
        try:
            home = subprocess.run(["/usr/libexec/java_home"], capture_output=True, text=True).stdout.strip()
            if home and os.path.exists(os.path.join(home, "bin", "javac")):
                return os.path.join(home, "bin", "javac")
        except OSError:
            pass
    return None


def compile_lib(javac, out_dir):
    lib = os.path.join(HERE, "lib")
    sources = []
    for root, _, files in os.walk(lib):
        sources += [os.path.join(root, f) for f in files if f.endswith(".java")]
    listfile = os.path.join(out_dir, "sources.txt")
    with open(listfile, "w") as f:
        f.write("\n".join('"' + s.replace("\\", "/") + '"' for s in sorted(sources)))
    classes = os.path.join(out_dir, "classes")
    os.makedirs(classes)
    # our own java.lang etc.: compile against nothing but these sources
    cmd = [javac, "-source", "8", "-target", "8", "-bootclasspath", "", "-sourcepath", lib, "-encoding", "ascii",
           "-nowarn", "-Xlint:-options", "-g:source,lines", "-d", classes, "@" + listfile]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.stderr.write(r.stdout + r.stderr)
        sys.exit("mkrt: javac failed")
    return classes


def make_jar(classes):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        names = []
        for root, _, files in os.walk(classes):
            for f in files:
                full = os.path.join(root, f)
                names.append((os.path.relpath(full, classes).replace(os.sep, "/"), full))
        for name, full in sorted(names):
            info = zipfile.ZipInfo(name, (2000, 1, 1, 0, 0, 0))     # fixed date: same bytes every build
            info.compress_type = zipfile.ZIP_DEFLATED
            with open(full, "rb") as fh:
                z.writestr(info, fh.read(), compresslevel=9)
    return buf.getvalue()


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    out = sys.argv[1]
    javac = find_javac()
    if not javac:
        print("mkrt: javac not found (install a JDK)")
        sys.exit(3)
    tmp = tempfile.mkdtemp(prefix="myos-javart-")
    try:
        data = make_jar(compile_lib(javac, tmp))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    if "--jar" in sys.argv:
        with open(sys.argv[sys.argv.index("--jar") + 1], "wb") as f:
            f.write(data)
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    lines = ["/* generated by ports/java/mkrt.py: the runtime library (ports/java/lib) as a jar */",
             "static const unsigned char rt_jar[%d] = {" % len(data)]
    for i in range(0, len(data), 24):
        lines.append(",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("mkrt: runtime library %d bytes" % len(data))


if __name__ == "__main__":
    main()
